-- Clean up existing tables (Ignored if they do not exist)
BEGIN
   FOR t IN (SELECT table_name FROM user_tables WHERE table_name IN (
      'QUIZ_ATTEMPT', 'SUBMISSION', 'CERTIFICATE', 'PAYMENT', 'REVIEW', 
      'ENROLLMENT', 'ANSWER_OPTION', 'QUESTION', 'QUIZ', 'ASSIGNMENT', 
      'LESSON', 'MODULE', 'COURSE', 'USERS', 'ADMIN'
   )) LOOP
      EXECUTE IMMEDIATE 'DROP TABLE ' || t.table_name || ' CASCADE CONSTRAINTS';
   END LOOP;
END;
/

-- ---------------------------------------------------------
-- 1. ADMIN
-- ---------------------------------------------------------
CREATE TABLE ADMIN (
    admin_id      NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR2(100) NOT NULL,
    email         VARCHAR2(150) NOT NULL UNIQUE,
    password_hash VARCHAR2(255) NOT NULL,
    access_level  VARCHAR2(50) DEFAULT 'standard',
    created_at    TIMESTAMP DEFAULT CURRENT_TIMESTAMP
);

-- ---------------------------------------------------------
-- 2. USERS (Students and Instructors)
-- ---------------------------------------------------------
CREATE TABLE USERS (
    user_id             NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    managed_by_admin_id NUMBER,
    name                VARCHAR2(100) NOT NULL,
    email               VARCHAR2(150) NOT NULL UNIQUE,
    password_hash       VARCHAR2(255) NOT NULL,
    role                VARCHAR2(20) DEFAULT 'student' CHECK (role IN ('student', 'instructor')),
    created_at          TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_users_admin FOREIGN KEY (managed_by_admin_id) REFERENCES ADMIN(admin_id) ON DELETE SET NULL
);

-- ---------------------------------------------------------
-- 3. COURSE
-- ---------------------------------------------------------
CREATE TABLE COURSE (
    course_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instructor_id        NUMBER NOT NULL,
    managed_by_admin_id  NUMBER,
    approved_by_admin_id NUMBER,
    title                VARCHAR2(200) NOT NULL,
    description          CLOB,
    price                NUMBER(10,2) DEFAULT 0.00,
    level_name           VARCHAR2(50) DEFAULT 'Beginner',
    approval_status      VARCHAR2(20) DEFAULT 'pending' CHECK (approval_status IN ('pending', 'approved', 'rejected')),
    approved_at          TIMESTAMP,
    created_at           TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_course_instructor FOREIGN KEY (instructor_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_course_admin_mgt FOREIGN KEY (managed_by_admin_id) REFERENCES ADMIN(admin_id) ON DELETE SET NULL,
    CONSTRAINT fk_course_admin_app FOREIGN KEY (approved_by_admin_id) REFERENCES ADMIN(admin_id) ON DELETE SET NULL
);

-- ---------------------------------------------------------
-- 4. MODULE
-- ---------------------------------------------------------
CREATE TABLE MODULE (
    module_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id   NUMBER NOT NULL,
    title       VARCHAR2(200) NOT NULL,
    order_index NUMBER DEFAULT 0,
    CONSTRAINT fk_module_course FOREIGN KEY (course_id) REFERENCES COURSE(course_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 5. LESSON
-- ---------------------------------------------------------
CREATE TABLE LESSON (
    lesson_id        NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    module_id        NUMBER NOT NULL,
    title            VARCHAR2(200) NOT NULL,
    content_type     VARCHAR2(50) DEFAULT 'video',
    video_url        VARCHAR2(255),
    duration_minutes NUMBER DEFAULT 0,
    order_index      NUMBER DEFAULT 0,
    CONSTRAINT fk_lesson_module FOREIGN KEY (module_id) REFERENCES MODULE(module_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 6. ASSIGNMENT
-- ---------------------------------------------------------
CREATE TABLE ASSIGNMENT (
    assignment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id     NUMBER NOT NULL,
    title         VARCHAR2(200) NOT NULL,
    instructions  CLOB,
    due_date      DATE,
    max_score     NUMBER DEFAULT 100,
    CONSTRAINT fk_assignment_lesson FOREIGN KEY (lesson_id) REFERENCES LESSON(lesson_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 7. QUIZ
-- ---------------------------------------------------------
CREATE TABLE QUIZ (
    quiz_id            NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    lesson_id          NUMBER NOT NULL,
    title              VARCHAR2(200) NOT NULL,
    time_limit_minutes NUMBER DEFAULT 30,
    passing_score      NUMBER DEFAULT 50,
    CONSTRAINT fk_quiz_lesson FOREIGN KEY (lesson_id) REFERENCES LESSON(lesson_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 8. QUESTION
-- ---------------------------------------------------------
CREATE TABLE QUESTION (
    question_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    quiz_id       NUMBER NOT NULL,
    question_text CLOB NOT NULL,
    question_type VARCHAR2(50) DEFAULT 'mcq',
    points        NUMBER DEFAULT 1,
    CONSTRAINT fk_question_quiz FOREIGN KEY (quiz_id) REFERENCES QUIZ(quiz_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 9. ANSWER_OPTION
-- ---------------------------------------------------------
CREATE TABLE ANSWER_OPTION (
    option_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    question_id NUMBER NOT NULL,
    option_text VARCHAR2(255) NOT NULL,
    is_correct  NUMBER(1) DEFAULT 0 CHECK (is_correct IN (0, 1)),
    CONSTRAINT fk_option_question FOREIGN KEY (question_id) REFERENCES QUESTION(question_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 10. ENROLLMENT (M:N Student to Course)
-- ---------------------------------------------------------
CREATE TABLE ENROLLMENT (
    enrollment_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          NUMBER NOT NULL,
    course_id        NUMBER NOT NULL,
    enrolled_at      TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    status           VARCHAR2(20) DEFAULT 'active' CHECK (status IN ('active', 'completed', 'dropped')),
    progress_percent NUMBER(5,2) DEFAULT 0.00,
    CONSTRAINT uq_enrollment UNIQUE (user_id, course_id),
    CONSTRAINT fk_enroll_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_enroll_course FOREIGN KEY (course_id) REFERENCES COURSE(course_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 11. REVIEW
-- ---------------------------------------------------------
CREATE TABLE REVIEW (
    review_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      NUMBER NOT NULL,
    course_id    NUMBER NOT NULL,
    rating       NUMBER(1) NOT NULL CHECK (rating BETWEEN 1 AND 5),
    comment_text CLOB,
    created_at   TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT uq_review UNIQUE (user_id, course_id),
    CONSTRAINT fk_review_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_review_course FOREIGN KEY (course_id) REFERENCES COURSE(course_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 12. PAYMENT
-- ---------------------------------------------------------
CREATE TABLE PAYMENT (
    payment_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    NUMBER NOT NULL,
    course_id  NUMBER NOT NULL,
    amount     NUMBER(10,2) NOT NULL,
    status     VARCHAR2(20) DEFAULT 'pending' CHECK (status IN ('pending', 'completed', 'refunded')),
    paid_at    TIMESTAMP,
    CONSTRAINT fk_payment_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_payment_course FOREIGN KEY (course_id) REFERENCES COURSE(course_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 13. CERTIFICATE
-- ---------------------------------------------------------
CREATE TABLE CERTIFICATE (
    certificate_id  NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         NUMBER NOT NULL,
    course_id       NUMBER NOT NULL,
    issued_at       TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    certificate_url VARCHAR2(255),
    CONSTRAINT uq_certificate UNIQUE (user_id, course_id),
    CONSTRAINT fk_cert_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_cert_course FOREIGN KEY (course_id) REFERENCES COURSE(course_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 14. SUBMISSION
-- ---------------------------------------------------------
CREATE TABLE SUBMISSION (
    submission_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       NUMBER NOT NULL,
    assignment_id NUMBER NOT NULL,
    file_url      VARCHAR2(255),
    submitted_at  TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    score         NUMBER,
    feedback      CLOB,
    CONSTRAINT fk_sub_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_sub_assignment FOREIGN KEY (assignment_id) REFERENCES ASSIGNMENT(assignment_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- 15. QUIZ_ATTEMPT
-- ---------------------------------------------------------
CREATE TABLE QUIZ_ATTEMPT (
    attempt_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      NUMBER NOT NULL,
    quiz_id      NUMBER NOT NULL,
    score        NUMBER,
    attempted_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_attempt_user FOREIGN KEY (user_id) REFERENCES USERS(user_id) ON DELETE CASCADE,
    CONSTRAINT fk_attempt_quiz FOREIGN KEY (quiz_id) REFERENCES QUIZ(quiz_id) ON DELETE CASCADE
);

-- ---------------------------------------------------------
-- Indexes for Performance Tuning
-- ---------------------------------------------------------
CREATE INDEX idx_course_instructor ON COURSE(instructor_id);
CREATE INDEX idx_module_course ON MODULE(course_id);
CREATE INDEX idx_lesson_module ON LESSON(module_id);
CREATE INDEX idx_enrollment_user ON ENROLLMENT(user_id);
CREATE INDEX idx_enrollment_course ON ENROLLMENT(course_id);
CREATE INDEX idx_submission_user ON SUBMISSION(user_id);
CREATE INDEX idx_attempt_user ON QUIZ_ATTEMPT(user_id);

COMMIT;
